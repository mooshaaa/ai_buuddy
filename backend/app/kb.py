_BY_ID = {e.id: e for e in ENTRIES}

STOP = {
    "что", "как", "это", "для", "мне", "про", "где", "когда", "надо", "нужно", "можно", "чего", "или", "при",
    "его", "она", "они", "ещё", "еще", "есть", "был", "быть", "мой", "моя", "мои", "свой", "меня", "тебе",
    "почему", "зачем", "какой", "какая", "какие", "нужен", "нужна", "такое", "эти", "это", "там", "тут",
}
_WORD = re.compile(r"[a-zа-яё0-9:]+")


def _stems(text: str) -> set[str]:
    return {w[:5] for w in _WORD.findall(text.lower()) if len(w) >= 3 and w not in STOP}


_INDEX = {e.id: (_stems(" ".join(e.tags)), _stems(e.title + " " + e.text)) for e in ENTRIES}


def get(entry_id: str) -> Entry | None:
    return _BY_ID.get(entry_id)


def for_role(role: str) -> list[Entry]:
    return [e for e in ENTRIES if role in e.roles]


def search(message: str, entries: list[Entry]) -> Entry | None:
    """Грубый поиск по основам слов (для заглушки и для определения темы без модели)."""
    q = _stems(message)
    best, best_key = None, (0, 0)
    for e in entries:
        tags, text = _INDEX[e.id]
        t, x = len(q & tags), len(q & text)
        if t == 0 and x < 2:
            continue
        key = (t * 3 + x, x)
        if key > best_key:
            best, best_key = e, key
    return best


def format_for_prompt(entries: list[Entry]) -> str:
    return "\n\n".join(f"[{e.id}] {e.title}\n{e.text}" for e in entries)
