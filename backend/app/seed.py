# Что у демонстрационного стажёра уже сделано
DEMO_DONE = {"Добавиться в чаты и каналы", "Запросить доступы"}


def seed(db: Session) -> None:
    if db.query(User).count():
        return
    for uid, name, role in USERS:
        db.add(User(id=uid, name=name, role=role))
    db.flush()
    pos: dict[tuple[str, str], int] = {}
    for role, period, title, desc in STAGES:
        n = pos.get((role, period), 0)
        pos[(role, period)] = n + 1
        st = Stage(role=role, period=period, position=n, title=title, description=desc)
        db.add(st)
        db.flush()
        for uid, _, urole in USERS:
            if urole == role:
                db.add(StageProgress(user_id=uid, stage_id=st.id, done=role == "intern" and title in DEMO_DONE))
    db.commit()
